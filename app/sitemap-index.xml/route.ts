import { NextResponse } from 'next/server';
import { targetPersonas, seoLocations, industries, seoGlossaryTerms } from '@/lib/pseo';
import { seoServices } from '@/lib/pseo/data/services';

/**
 * SITEMAP INDEX - Google Compliant
 * 
 * This is the master sitemap that tells Google where all our individual sitemaps are.
 * Submit THIS URL to Google Search Console: https://anthroly.com/sitemap-index.xml
 * 
 * Google Requirements:
 * ✅ Max 50,000 URLs per sitemap
 * ✅ Max 50MB per sitemap file
 * ✅ UTF-8 encoding
 * ✅ All URLs from single host
 * ✅ Sitemap index for large sites
 */

const URLS_PER_SITEMAP = 10000;
const baseUrl = 'https://anthroly.com';

function getLastMod(): string {
  return new Date().toISOString().split('T')[0];
}

export async function GET() {
  const lastmod = getLastMod();
  
  // Calculate number of sitemaps needed for each category
  const personaIndustryLocationCount = targetPersonas.length * industries.length * seoLocations.length;
  const personaIndustryLocationSitemaps = Math.ceil(personaIndustryLocationCount / URLS_PER_SITEMAP);
  
  const serviceIndustryLocationCount = seoServices.length * industries.length * seoLocations.length;
  const serviceIndustryLocationSitemaps = Math.ceil(serviceIndustryLocationCount / URLS_PER_SITEMAP);
  
  // Only 30% of glossary terms (high-value)
  const highValueGlossaryCount = 20; // ~30% of 60 terms
  const glossaryIndustryLocationCount = highValueGlossaryCount * industries.length * seoLocations.length;
  const glossaryIndustryLocationSitemaps = Math.ceil(glossaryIndustryLocationCount / URLS_PER_SITEMAP);
  
  const sitemaps: string[] = [];
  
  // Main sitemap (generated by Next.js at /sitemap.xml)
  sitemaps.push(`  <sitemap>
    <loc>${baseUrl}/sitemap.xml</loc>
    <lastmod>${lastmod}</lastmod>
  </sitemap>`);
  
  // Persona × Industry × Location sitemaps
  for (let i = 0; i < personaIndustryLocationSitemaps; i++) {
    sitemaps.push(`  <sitemap>
    <loc>${baseUrl}/sitemaps/persona-industry-location/${i}</loc>
    <lastmod>${lastmod}</lastmod>
  </sitemap>`);
  }
  
  // Service × Industry × Location sitemaps
  for (let i = 0; i < serviceIndustryLocationSitemaps; i++) {
    sitemaps.push(`  <sitemap>
    <loc>${baseUrl}/sitemaps/service-industry-location/${i}</loc>
    <lastmod>${lastmod}</lastmod>
  </sitemap>`);
  }
  
  // Glossary × Industry × Location sitemaps
  for (let i = 0; i < glossaryIndustryLocationSitemaps; i++) {
    sitemaps.push(`  <sitemap>
    <loc>${baseUrl}/sitemaps/glossary-industry-location/${i}</loc>
    <lastmod>${lastmod}</lastmod>
  </sitemap>`);
  }
  
  const xml = `<?xml version="1.0" encoding="UTF-8"?>
<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${sitemaps.join('\n')}
</sitemapindex>`;

  return new NextResponse(xml, {
    headers: {
      'Content-Type': 'application/xml',
      'Cache-Control': 'public, max-age=3600, s-maxage=3600',
    },
  });
}
